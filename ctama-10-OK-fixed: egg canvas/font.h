void mysdl_draw_char(MySDL* app, int x, int y, char c, Uint32 color) {
    uint8_t index = (uint8_t)c;
    for (int row = 0; row < 8; row++) {
        uint8_t line = DOS_FONT_8X8[index][row];
        for (int col = 0; col < 8; col++) {
            if (line & (1 << (7 - col))) {
                mysdl_draw_pixel(app, x + col, y + row, color);
            }
        }
    }
}

void mysdl_draw_text(MySDL* app, int x, int y, const char* str, Uint32 color) {
    int cur_x = x;
    int cur_y = y;
    while (*str) {
        if (*str == '\n') {
            cur_x = x;
            cur_y += 8;
        } else {
            mysdl_draw_char(app, cur_x, cur_y, *str, color);
            cur_x += 8;
        }
        str++;
    }
}

