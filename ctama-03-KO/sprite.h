void mysdl_draw_sprite16(MySDL* app, int x, int y, const uint8_t* sprite_data, const unsigned int* palette) {
    for (int row = 0; row < 16; row++) {
        for (int col = 0; col < 16; col++) {
            uint8_t pixel = sprite_data[row * 16 + col];
            if (pixel != 0xFF) {
                mysdl_draw_pixel(app, x + col, y + row, palette[pixel]);
            }
        }
    }
}

